#   2. Run `brew update-python-resources obsidian-bib-sync` to fill in the `resource` blocks.
class ObsidianBibSync < Formula
  include Language::Python::Virtualenv

  desc "Sync Obsidian paper notes to BibTeX files across your machine"
  homepage "https://github.com/OWNER/obsidian-bib-sync"
  url "https://github.com/OWNER/obsidian-bib-sync/archive/refs/tags/v0.1.0.tar.gz"
  sha256 "REPLACE_WITH_TARBALL_SHA256"
  license "MIT"
  head "https://github.com/OWNER/obsidian-bib-sync.git", branch: "main"

  depends_on "python@3.13"

  # resource "..." do ... end  (generated by `brew update-python-resources`)

  def install
    virtualenv_install_with_resources
  end

  # `brew services start obsidian-bib-sync` runs the daemon at login and keeps it alive.
  service do
    run [opt_bin/"obib", "run"]
    keep_alive true
    log_path var/"log/obsidian-bib-sync.log"
    error_log_path var/"log/obsidian-bib-sync.log"
  end

  test do
    assert_match "obib", shell_output("#{bin}/obib --version")
  end
end
